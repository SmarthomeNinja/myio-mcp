// npm run sync-modbus - a Modbus sablon-gyujtemeny (a V4-repo WEB_cdn/modbus/*.json fajljai = az okoslak.hu/ext2/modbus/ forrasa)
// pillanatkepe a csomag modbus_templates.json-jaba: a myio_modbus_templates / myio_modbus_discover eszkozok tartaleka, ha a CDN nem
// erheto el (es amig a CDN-en a regi, v1-es index van). Determinisztikus (nincs benne datum), a `pack` is ezzel kezd.
//   --check   csak ellenoriz: kilepesi kod 1, ha elter
//   MYIO_MODBUS_SRC=<mappa>   mas forras
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = process.env.MYIO_MODBUS_SRC || path.resolve(ROOT, '..', 'WEB_cdn', 'modbus');
const dst = path.join(ROOT, 'modbus_templates.json');
const check = process.argv.includes('--check');

if (!fs.existsSync(src)) {
  console.warn(`sync-modbus: source not found (${src}) - the bundled modbus_templates.json is kept as it is`);
  process.exit(check ? 1 : 0);
}
const tpl = {};
for (const fn of fs.readdirSync(src).filter(f => f.endsWith('.json') && f !== 'index.json').sort()) {
  const t = JSON.parse(fs.readFileSync(path.join(src, fn), 'utf8'));
  const id = fn.slice(0, -5);
  if (t.id !== id || !Array.isArray(t.blk)) { console.error(`sync-modbus: ${fn} is not a template (id / blk) - run tools/mb_tpl_add.py --check in the V4 repo`); process.exit(1); }
  tpl[id] = t;
}
const out = JSON.stringify({ what: 'snapshot of the myIO Modbus template collection (WEB_cdn/modbus) - generated by npm run sync-modbus', tpl }) + '\n';
const cur = fs.existsSync(dst) ? fs.readFileSync(dst, 'utf8') : '';
if (out === cur) { console.log(`sync-modbus: up to date (${Object.keys(tpl).length} templates, ${out.length} B)`); process.exit(0); }
if (check) { console.error(`sync-modbus: modbus_templates.json is OUT OF DATE (${cur.length} B bundled, ${out.length} B from the source) - run npm run sync-modbus`); process.exit(1); }
fs.writeFileSync(dst, out);
console.log(`sync-modbus: wrote modbus_templates.json (${Object.keys(tpl).length} templates, ${out.length} B)`);
